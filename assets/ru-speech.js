/* ===== Білім Аралы — «исправитель произношения» для голоса браузера (русский язык) =====
   Зачем: когда у фразы нет записанного mp3, Барсика озвучивает сам браузер, и ему отдаётся тот же текст,
   что на экране. Сокращения он читает неверно («8 см» → «восемь смотри»), а слова с двумя ударениями —
   по умолчанию («стоит» → «сто́ит», хотя в задачах «стои́т» = «находится»).
   Что делает: перед озвучкой превращает текст в «говорящий»:
     • единицы после чисел и отдельно: см, мм, дм, км, м, кг, г, л, мл, т, ц, ч, мин, сек, га, тг/₸, км/ч, м/с,
       квадратные и кубические (см², м², дм³ …) — полными словами с правильным окончанием (1 сантиметр, 2 сантиметра, 5 сантиметров);
     • %, ° и °C — «процентов», «градусов», «градусов Цельсия»;
     • знаки действий между числами: · × ÷ − = + и « : » — словами;
     • «стоит / стоят» в значении «находится» — заменяются на «находится / находятся» (любой голос ставит ударение верно);
       если рядом слова про деньги (тг, цена, купить, «сколько стоит» …), слово не трогается — там «сто́ит» верно.
   На экране текст не меняется — правится только то, что уходит в синтезатор речи.
   Как пользоваться: RUSPEECH.fix('Найди площадь со сторонами 8 см и 9 см.') → строка для озвучки.
   Скрипт ещё и сам оборачивает speechSynthesis.speak: любой русский текст проходит через fix().
   Свои слова добавлять в таблицу WORDS ниже: [регулярное выражение, замена]. */
(function(){
  if(window.RUSPEECH) return;

  function pl(n, a, b, c, frac){            /* склонение: 1 / 2–4 / 5+ ; дробные числа — как «2,5 сантиметра» */
    if(frac) return b;
    n = Math.abs(n); var m = n % 100, d = n % 10;
    if(m > 10 && m < 15) return c;
    if(d === 1) return a;
    if(d > 1 && d < 5) return b;
    return c;
  }

  /* единица → [1, 2–4, 5+] */
  var U = {
    'см':['сантиметр','сантиметра','сантиметров'], 'мм':['миллиметр','миллиметра','миллиметров'],
    'дм':['дециметр','дециметра','дециметров'],   'км':['километр','километра','километров'],
    'м':['метр','метра','метров'],                'кг':['килограмм','килограмма','килограммов'],
    'г':['грамм','грамма','граммов'],             'мг':['миллиграмм','миллиграмма','миллиграммов'],
    'л':['литр','литра','литров'],                'мл':['миллилитр','миллилитра','миллилитров'],
    'т':['тонна','тонны','тонн'],                 'ц':['центнер','центнера','центнеров'],
    'ч':['час','часа','часов'],                   'мин':['минута','минуты','минут'],
    'сек':['секунда','секунды','секунд'],         'га':['гектар','гектара','гектаров'],
    'тг':['тенге','тенге','тенге'],               '₸':['тенге','тенге','тенге'],
    'см²':['квадратный сантиметр','квадратных сантиметра','квадратных сантиметров'],
    'мм²':['квадратный миллиметр','квадратных миллиметра','квадратных миллиметров'],
    'дм²':['квадратный дециметр','квадратных дециметра','квадратных дециметров'],
    'м²':['квадратный метр','квадратных метра','квадратных метров'],
    'км²':['квадратный километр','квадратных километра','квадратных километров'],
    'см³':['кубический сантиметр','кубических сантиметра','кубических сантиметров'],
    'дм³':['кубический дециметр','кубических дециметра','кубических дециметров'],
    'м³':['кубический метр','кубических метра','кубических метров']
  };
  /* «в единицу времени»: 60 км/ч → «60 километров в час» */
  var RATE = { 'км/ч':['километр','километра','километров','час'], 'м/с':['метр','метра','метров','секунду'],
               'м/мин':['метр','метра','метров','минуту'], 'км/с':['километр','километра','километров','секунду'] };

  var L = '\\u0400-\\u04FFa-zA-Z0-9';   /* вся кириллица (и казахские буквы тоже) + латиница + цифры */
  var NUM = '(\\d+(?:[.,]\\d+)?)';
  function plain(s){ return String(s).toLowerCase(); }
  function isFrac(s){ return /[.,]/.test(s); }

  /* список единиц для регулярки: длинные раньше коротких */
  var keys = Object.keys(U).concat(Object.keys(RATE)).sort(function(a, b){ return b.length - a.length; })
    .map(function(k){ return k.replace(/[\/²³]/g, function(c){ return c === '/' ? '\\/' : c; }); });
  var AFTER_NUM = new RegExp(NUM + '[\\s\\u00a0]?(' + keys.join('|') + ')(?![' + L + '²³])', 'g');
  var STAND_ALONE = /(^|[^\u0400-\u04FFa-zA-Z0-9²³\/])(см²|мм²|дм²|м²|км²|см³|дм³|м³|см|мм|дм|км|кг|мл|мг|тг|₸)(?![\u0400-\u04FFa-zA-Z0-9²³\/-])(?!\.\s+[а-яё])/g;

  /* «в 1 м», «на 1 см» — после предлога единица стоит в предложном падеже: «в одном метре» */
  var PREP = { 'см':'одном сантиметре', 'мм':'одном миллиметре', 'дм':'одном дециметре', 'км':'одном километре', 'м':'одном метре',
               'кг':'одном килограмме', 'г':'одном грамме', 'л':'одном литре', 'мл':'одном миллилитре', 'т':'одной тонне',
               'ц':'одном центнере', 'ч':'одном часе', 'мин':'одной минуте', 'сек':'одной секунде', 'га':'одном гектаре' };
  function units(t){
    t = t.replace(AFTER_NUM, function(all, n, u, off, str){
      var num = parseFloat(String(n).replace(',', '.')), fr = isFrac(n), before = str.slice(Math.max(0, off - 6), off);
      if(RATE[u]){ var r = RATE[u]; return n + ' ' + pl(num, r[0], r[1], r[2], fr) + ' в ' + r[3]; }
      /* «в 2024 г.» — это год, а не граммы; «1000 г» после «1 кг» — граммы */
      if(u === 'г' && !fr && num >= 1000 && num <= 2100 && /(^|[^а-яё])(в|с|до|к|от|по|на)\s$/i.test(before) && str.charAt(off + all.length) === '.') return all;
      if(num === 1 && !fr && PREP[u] && /(^|[^а-яё])(в|на|при)\s$/i.test(before)) return PREP[u];
      var f = U[u]; if(!f) return all;
      return n + ' ' + pl(num, f[0], f[1], f[2], fr);
    });
    /* единицы без числа: «Сколько см в 1 м?» */
    t = t.replace(STAND_ALONE, function(all, pre, u, off, str){ var f = U[u]; if(!f) return all; return pre + (pre === '(' && str.charAt(off + all.length) === ')' ? f[0] : f[2]); });
    return t;
  }

  function signs(t){
    /* знаки действий — до замены %, ° (чтобы «360° : 60 = 6°» тоже читалось) */
    t = t.replace(/([\d°%²³])\s*[·×∙*]\s*(?=\d)/g, '$1 умножить на ')
         .replace(/([\d°%²³])\s*÷\s*(?=\d)/g, '$1 разделить на ')
         .replace(/([\d°%²³])\s+:\s+(?=\d)/g, '$1 разделить на ')
         .replace(/(\d)\s*[−–]\s+(?=\d)/g, '$1 минус ')
         .replace(/(\d)\s+-\s+(?=\d)/g, '$1 минус ')
         .replace(/(\d)\s*\+\s*(?=\d)/g, '$1 плюс ')
         .replace(/\s=\s/g, ' равно ')
         .replace(/(\d|\))=(?=\d|\()/g, '$1 равно ');
    t = t.replace(new RegExp(NUM + '\\s?%', 'g'), function(all, n){ return n + ' ' + pl(parseFloat(String(n).replace(',', '.')), 'процент', 'процента', 'процентов', isFrac(n)); });
    t = t.replace(new RegExp(NUM + '\\s?°(?:\\s?([CС])(?![' + L + ']))?', 'g'), function(all, n, c){
      var w = pl(parseFloat(String(n).replace(',', '.')), 'градус', 'градуса', 'градусов', isFrac(n));
      return n + ' ' + w + (c ? ' Цельсия' : '');
    });
    return t;
  }

  /* «стоит/стоят» = «находится/находятся» (ударение на «и/я»). Про деньги — не трогаем: там «сто́ит» верно. */
  var COST = /(тг|тенге|₸|\$|руб|монет|цен[аыуеой]|стоимост|деньг|сдач|дорог|дешев|куп|покуп|заплат|доллар|евро|скидк|сколько\s+(?:стоит|стоят)|сумм[аыу]\s+(?:покупки|заказа))/i;
  var STOIT = /(^|[^а-яёА-ЯЁ])(С|с)то(ит|ят)(?![а-яёА-ЯЁ])(?!\s+ли(?![а-яёА-ЯЁ]))(?!\s+[а-яё]+(?:ть|ться|чь)(?![а-яёА-ЯЁ]))/g;   /* «стоит делать», «стоит ли» — это «имеет смысл», там «сто́ит» верно */
  function stress(t){
    return t.replace(/[^.!?…]+[.!?…]*/g, function(sn){
      if(!/то(ит|ят)/i.test(sn) || COST.test(sn)) return sn;
      return sn.replace(STOIT, function(all, pre, c, e, off, str){
        if(/(^|[^а-яё])не\s$/i.test(str.slice(Math.max(0, off - 4), off + pre.length)) && /^\s*[.!?…,;:)»"]*\s*$/.test(str.slice(off + all.length))) return all;   /* «так делать не стоит» */
        var w = e === 'ит' ? 'находится' : 'находятся';
        return pre + (c === 'С' ? 'Н' + w.slice(1) : w);
      });
    });
  }

  /* Свои слова: [что искать, на что менять]. Сюда добавляем то, что браузер читает неверно. */
  var WORDS = [
    /* пример: [/(^|[^а-яё])замок(?![а-яё])/gi, '$1замок'] */
  ];
  function words(t){ WORDS.forEach(function(w){ t = t.replace(w[0], w[1]); }); return t; }

  function fix(text){
    if(text == null) return text;
    var t = String(text);
    if(!/[а-яёА-ЯЁ]/.test(t) && !/\d\s?(?:см|мм|дм|км|кг|мл|%|°)/.test(t)) return t;
    t = t.replace(/<sup>\s*([23])\s*<\/sup>/gi, function(a, d){ return d === '2' ? '²' : '³'; }).replace(/<[^>]+>/g, ' ');
    t = units(t); t = signs(t); t = stress(t); t = words(t);
    return t.replace(/\s{2,}/g, ' ');
  }

  window.RUSPEECH = { fix:fix, units:units, stress:stress, WORDS:WORDS };

  /* Страховка: любой русский текст, который уходит в синтезатор браузера, проходит через fix(). */
  try {
    var ss = window.speechSynthesis;
    if(ss && !ss.__ruFix && typeof ss.speak === 'function'){
      var orig = ss.speak.bind(ss);
      ss.speak = function(u){
        try { if(u && typeof u.text === 'string' && /[а-яёА-ЯЁ]/.test(u.text) && (!u.lang || /^ru/i.test(u.lang))) u.text = fix(u.text); } catch(e){}
        return orig(u);
      };
      ss.__ruFix = true;
    }
  } catch(e){}
})();
